/** Escape any value for safe HTML output. */
function e($value)
{
    return htmlspecialchars((string) $value, ENT_QUOTES, "UTF-8");
}

/** True when a user session is active. */
function is_logged_in()
{
    return isset($_SESSION["user_id"], $_SESSION["role"]);
}

/** Send guests back to the login page. */
function require_login()
{
    if (!is_logged_in()) {
        header("Location: index.php");
        exit;
    }
}

/** Only allow administrators, everyone else goes to their home page. */
function require_admin()
{
    require_login();

    if ($_SESSION["role"] !== "admin") {
        header("Location: home.php");
        exit;
    }
}

/** Redirect a user to the correct landing page based on role. */
function redirect_by_role($role)
{
    header("Location: " . ($role === "admin" ? "admin.php" : "home.php"));
    exit;
}

/** First letter of the username, used for the avatar bubble. */
function initial($username)
{
    return strtoupper(substr($username, 0, 1));
}

